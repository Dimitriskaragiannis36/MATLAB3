% Ορισμός δεδομένων
A = [16 -8 2 1; 
     2 -12 1 0;
    -1 1 -4 1; 
     0 -1 2 3];
y = [1; 1; 1; 1];
tol = 1/2*10^-6;
maxiter = 100;

% Εύρεση πραγματικών ιδιοτιμών για σύγκριση
idiotimes = eig(A);
% Ταξινόμηση κατά φθίνουσα απόλυτη τιμή (όπως ορίζει η θεωρία |λ1| > |λ2| > ... > |λn|)
[~, idx] = sort(abs(idiotimes), 'descend');
sorted_eig = idiotimes(idx);
l1 = sorted_eig(1);
l4 = sorted_eig(4);

fprintf('Η μέγιστη κατά μέτρο ιδιοτιμή (λ1) είναι: %.6f\n', l1);
fprintf('Η ελάχιστη κατά μέτρο ιδιοτιμή (λ4) είναι: %.6f\n\n', l4);

% ======== ΜΕΡΟΣ Α: Υπολογισμός λ1 ========
q_values1 = l1 - 0.3 : -0.1 : l1 - 0.9;

disp('=====================================================================');
disp('                    Υπολογισμός των (λ1, x(1))');
disp('                   Αντίστροφη μέθοδος των δυνάμεων');
disp('---------------------------------------------------------------------');
fprintf('%-12s | %-12s | %-12s | %-20s\n', 'Μετατόπιση q', 'Επαναλήψεις', 'Ιδιοτιμή λ1', 'Ιδιοδιάνυσμα x(1)');
disp('---------------------------------------------------------------------');

time_eig_power_l1 = tic;
for q = q_values1
    [lambda, z, itcount] = eig_power_gauss(A, y, q, tol, maxiter);
    z_str = sprintf('[%.4f, %.4f, %.4f, %.4f]', z(1), z(2), z(3), z(4));
    fprintf('%-12.4f | %-12d | %-12.6f | %s\n', q, itcount, lambda, z_str);
end
t_power1 = toc(time_eig_power_l1);

disp('---------------------------------------------------------------------');
disp('                   Μέθοδος Πηλίκων Rayleigh');
disp('---------------------------------------------------------------------');
fprintf('%-12s | %-12s | %-12s | %-20s\n', 'Μετατόπιση q', 'Επαναλήψεις', 'Ιδιοτιμή λ1', 'Ιδιοδιάνυσμα x(1)');
disp('---------------------------------------------------------------------');

time_rayleigh_l1 = tic;
for q = q_values1
    [lambda, z, itcount] = rayleigh_gauss(A, y, q, tol, maxiter);
    z_str = sprintf('[%.4f, %.4f, %.4f, %.4f]', z(1), z(2), z(3), z(4));
    fprintf('%-12.4f | %-12d | %-12.6f | %s\n', q, itcount, lambda, z_str);
end
t_ray1 = toc(time_rayleigh_l1);


% ======== ΜΕΡΟΣ Β: Υπολογισμός λ4 ========
q_values4 = l4 + 0.3 : 0.1 : l4 + 0.9;

disp(' ');
disp('=====================================================================');
disp('                    Υπολογισμός των (λ4, x(4))');
disp('                   Αντίστροφη μέθοδος των δυνάμεων');
disp('---------------------------------------------------------------------');
fprintf('%-12s | %-12s | %-12s | %-20s\n', 'Μετατόπιση q', 'Επαναλήψεις', 'Ιδιοτιμή λ4', 'Ιδιοδιάνυσμα x(4)');
disp('---------------------------------------------------------------------');

time_eig_power_l4 = tic;
for q = q_values4
    [lambda, z, itcount] = eig_power_gauss(A, y, q, tol, maxiter);
    z_str = sprintf('[%.4f, %.4f, %.4f, %.4f]', z(1), z(2), z(3), z(4));
    fprintf('%-12.4f | %-12d | %-12.6f | %s\n', q, itcount, lambda, z_str);
end
t_power4 = toc(time_eig_power_l4);

disp('---------------------------------------------------------------------');
disp('                   Μέθοδος Πηλίκων Rayleigh');
disp('---------------------------------------------------------------------');
fprintf('%-12s | %-12s | %-12s | %-20s\n', 'Μετατόπιση q', 'Επαναλήψεις', 'Ιδιοτιμή λ4', 'Ιδιοδιάνυσμα x(4)');
disp('---------------------------------------------------------------------');

time_rayleigh_l4 = tic;
for q = q_values4
    [lambda, z, itcount] = rayleigh_gauss(A, y, q, tol, maxiter);
    z_str = sprintf('[%.4f, %.4f, %.4f, %.4f]', z(1), z(2), z(3), z(4));
    fprintf('%-12.4f | %-12d | %-12.6f | %s\n', q, itcount, lambda, z_str);
end
t_ray4 = toc(time_rayleigh_l4);

% ======== ΧΡΟΝΟΙ ========
disp(' ');
disp('================ ΧΡΟΝΟΙ ΕΚΤΕΛΕΣΗΣ ================');
fprintf('Αντίστροφη Δυνάμεων (Λ1): %.6f s\n', t_power1);
fprintf('Πηλίκα Rayleigh (Λ1):    %.6f s\n', t_ray1);
fprintf('Αντίστροφη Δυνάμεων (Λ4): %.6f s\n', t_power4);
fprintf('Πηλίκα Rayleigh (Λ4):    %.6f s\n', t_ray4);